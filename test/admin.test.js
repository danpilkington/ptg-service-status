test("service creation, edits and removal preserve linked history", async t => {
    const dir = await fs.mkdtemp(path.join(os.tmpdir(), "ptg-catalog-"));
    const file = path.join(dir,"status.json");
    await fs.writeFile(file, JSON.stringify({services:[],incidents:[],maintenance:[]}));
    const key="catalog-test-key-at-least-24-characters";
    const app=express(); app.use(express.json()); attach(app,{statusFile:file,key});
    const server=app.listen(0,"127.0.0.1");
    await new Promise(resolve=>server.once("listening",resolve));
    t.after(async()=>{await new Promise(resolve=>server.close(resolve));await fs.unlink(file);await fs.rmdir(dir);});
    const url="http://127.0.0.1:"+server.address().port+"/api/admin/status";
    let snapshot=await (await fetch(url,{headers:{Authorization:"Bearer "+key}})).json();
    const put=body=>fetch(url,{method:"PUT",headers:{Authorization:"Bearer "+key,"Content-Type":"application/json"},body:JSON.stringify(body)});
    const save=async()=>{const r=await put(snapshot);assert.equal(r.status,200,await r.clone().text());snapshot=await r.json();};
    snapshot.data.services.push({id:"printing",name:"Printing",description:"Office printers",status:"operational"});
    await save();
    assert.equal(snapshot.data.services[0].description,"Office printers");
    for(const patch of [{id:"identity"},{name:" "},{description:"x".repeat(501)}]){
        const invalid=structuredClone(snapshot);Object.assign(invalid.data.services[0],patch);
        assert.equal((await put(invalid)).status,400);
    }
    snapshot.data.incidents=[{id:"print-incident",serviceId:"printing",title:"Printing delayed",message:"Investigating queues",start:"2026-09-17T10:00:00Z",phase:"investigating"}];
    await save();
    let removal=structuredClone(snapshot);removal.data.services=[];
    assert.equal((await put(removal)).status,400);
    snapshot.data.services[0].name="Office printing";snapshot.data.services[0].status="degraded";
    await save();assert.equal(snapshot.data.incidents[0].service,"Office printing");
    snapshot.data.incidents[0].phase="resolved";
    snapshot.data.maintenance=[{id:"upgrade",serviceId:"printing",title:"Upgrade",message:"Updating printers",start:"2026-09-20T10:00:00Z",end:"2026-09-20T11:00:00Z"}];
    await save();
    removal=structuredClone(snapshot);removal.data.services=[];
    assert.equal((await put(removal)).status,400);
    snapshot.data.maintenance=[];snapshot.data.services=[];
    await save();assert.equal(snapshot.data.incidents[0].service,"Office printing");
    assert.equal(snapshot.data.retiredServices[0].id,"printing");
    await save();assert.equal(snapshot.data.incidents[0].phase,"resolved");
    const reuse=structuredClone(snapshot);reuse.data.services=[{id:"printing",name:"Different printing",status:"operational"}];
    assert.equal((await put(reuse)).status,400);
    const reopen=structuredClone(snapshot);reopen.data.incidents[0].phase="investigating";
    assert.equal((await put(reopen)).status,400);
    const forged=structuredClone(snapshot);forged.data.incidents.push({...forged.data.incidents[0],id:"forged"});
    assert.equal((await put(forged)).status,400);
});
