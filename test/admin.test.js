test("publishing validates, authenticates, persists and detects conflicts", async t => {
    const dir = await fs.mkdtemp(path.join(os.tmpdir(), "ptg-status-"));
    const file = path.join(dir, "status.json");
    const original = { publishedAt: "2026-09-01T00:00:00Z", services: [{id:"vpn", name:"VPN",status:"operational"}], incidents:[],maintenance:[],supportUrls:{vpn:"https://example.com/support"} };
    await fs.writeFile(file, JSON.stringify(original));
    const key = "test-only-key-for-publishing-12345";
    const app = express(); app.use(express.json()); attach(app,{statusFile:file,key});
    const server = app.listen(0,"127.0.0.1");
    await new Promise(resolve=>server.once("listening",resolve));
    t.after(async()=>{await new Promise(resolve=>server.close(resolve)); await fs.unlink(file); await fs.rmdir(dir);});
    const url = "http://127.0.0.1:" + server.address().port + "/api/admin/status";
    const send=(method="GET",body,extra={})=>fetch(url,{method,headers:{Authorization:"Bearer "+key,"Content-Type":"application/json",...extra},...(body?{body:JSON.stringify(body)}:{})});
    assert.equal((await fetch(url)).status,401);
    assert.equal((await send("GET",null,{Authorization:"Bearer wrong"})).status,401);
    const snapshot=await (await send()).json();
    assert.equal((await send("PUT",{...snapshot},{Origin:"https://attacker.example"})).status,403);
    const bad=structuredClone(snapshot);bad.data.services[0].status="invented";
    assert.equal((await send("PUT",bad)).status,400);
    const invalidEvent=structuredClone(snapshot);
    invalidEvent.data.maintenance=[{id:"m",serviceId:"vpn",title:"Upgrade",message:"Brief interruption",start:"2026-09-20T12:00:00Z",end:"2026-09-20T11:00:00Z"}];
    assert.equal((await send("PUT",invalidEvent)).status,400);
    const duplicate=structuredClone(snapshot);duplicate.data.services.push(duplicate.data.services[0]);
    assert.equal((await send("PUT",duplicate)).status,400);
    assert.deepEqual(JSON.parse(await fs.readFile(file,"utf8")),original);
    snapshot.data.services[0].status="degraded";
    snapshot.data.incidents=[{id:"i",serviceId:"vpn",title:"VPN slow",message:"Investigating",start:"2026-09-16T12:00:00Z"}];
    snapshot.data.maintenance=[{id:"m",serviceId:"vpn",title:"Upgrade",message:"Brief interruption",start:"2026-09-20T12:00:00Z",end:"2026-09-20T13:00:00Z"}];
    const response=await send("PUT",snapshot);assert.equal(response.status,200);
    const saved=await response.json();assert.notEqual(saved.revision,snapshot.revision);
    assert.equal(saved.data.services[0].statusText,"Degraded performance");
    assert.equal(saved.data.incidents[0].service,"VPN");
    assert.equal(saved.data.maintenance[0].status,"maintenance");
    assert.deepEqual(saved.data.supportUrls,original.supportUrls);
    assert.deepEqual(JSON.parse(await fs.readFile(file,"utf8")),saved.data);
    assert.equal((await send("PUT",snapshot)).status,409);
    saved.data.incidents[0].phase="resolved";saved.data.incidents[0].pendingUpdate="Connectivity restored.";saved.data.maintenance=[];saved.data.services[0].status="operational";

    const resolution = await send("PUT",saved);
    assert.equal(resolution.status,200);
    const resolved = await resolution.json();
    assert.equal(resolved.data.incidents[0].phase,"resolved");
    assert.equal(resolved.data.incidents[0].updates.length,2);
    assert.equal(resolved.data.incidents[0].updates[1].message,"Connectivity restored.");
    const correction = structuredClone(resolved);
    correction.data.incidents[0].updateCorrections=[{id:correction.data.incidents[0].updates[0].id,message:"Investigating VPN connectivity.",phase:"investigating",impact:"unknown",workaround:"",nextUpdateAt:""}];
    const correctedResponse=await send("PUT",correction);assert.equal(correctedResponse.status,200);
    const corrected=await correctedResponse.json();
    assert.equal(corrected.data.incidents[0].updates[0].message,"Investigating VPN connectivity.");
    assert.equal(corrected.data.incidents[0].updates[0].at,resolved.data.incidents[0].updates[0].at);
    assert.equal(corrected.data.incidents[0].updateCorrections,undefined);
    const invalidCorrection=structuredClone(corrected);
    invalidCorrection.data.incidents[0].updateCorrections=[{id:"unknown",message:"Forged correction",phase:"investigating",impact:"unknown",workaround:"",nextUpdateAt:""}];
    assert.equal((await send("PUT",invalidCorrection)).status,400);
    const deletion=structuredClone(corrected);
    deletion.data.incidents[0].deletedUpdateIds=[deletion.data.incidents[0].updates[1].id];
    const deletionResponse=await send("PUT",deletion);assert.equal(deletionResponse.status,200);
    const trimmed=await deletionResponse.json();
    assert.equal(trimmed.data.incidents[0].updates.length,1);
    assert.equal(trimmed.data.incidents[0].updates[0].message,"Investigating VPN connectivity.");
    assert.equal(trimmed.data.incidents[0].deletedUpdateIds,undefined);
    const invalidDeletion=structuredClone(trimmed);
    invalidDeletion.data.incidents[0].deletedUpdateIds=["unknown"];
    assert.equal((await send("PUT",invalidDeletion)).status,400);
    const deleted = structuredClone(trimmed); deleted.data.incidents = [];
    assert.equal((await send("PUT",deleted)).status,400);
    const invalidImpact = structuredClone(trimmed);
    invalidImpact.data.microsoftAssessments=[{id:"MS1",impact:"invented"}];
    assert.equal((await send("PUT",invalidImpact)).status,400);
    trimmed.data.microsoftAssessments=[{id:"MS1",impact:"confirmed",note:"Staff affected."}];
    trimmed.data.incidents[0].updates=[{id:"fake",at:"2000-01-01",message:"Forged update"}];
    const assessedResponse = await send("PUT",trimmed);
    assert.equal(assessedResponse.status,200);
    const assessed = await assessedResponse.json();
    assert.equal(assessed.data.microsoftAssessments[0].impact,"confirmed");
    assert.equal(assessed.data.incidents[0].updates.length,1);
    assert.equal(assessed.data.incidents[0].updates[0].message,"Investigating VPN connectivity.");

});
